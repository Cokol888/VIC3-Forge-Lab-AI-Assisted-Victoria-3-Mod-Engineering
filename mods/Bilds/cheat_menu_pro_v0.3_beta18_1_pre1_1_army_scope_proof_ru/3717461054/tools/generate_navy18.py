def load(): return json.loads(REG.read_text(encoding='utf-8')), json.loads(CAT.read_text(encoding='utf-8'))
def provider_gate(h): return 'always = yes' if h.get('provider')=='vanilla' else ('cmp_provider_tech_res_active = yes' if h.get('provider')=='tech_res' else 'always = no')
def tech_gate(h): return 'always = yes' if not h.get('unlock_technology') else f"has_technology_researched = {h['unlock_technology']}"
def hvar(r): return f'cmp_navy18_comp2_row_{r}_hull_index'
def cvar(r): return f'cmp_navy18_comp2_row_{r}_count'
def selected_hull_cond(r,idx): return f'var:{hvar(r)} = {idx}'
def count_cond(r,a): return f'NOT = {{ has_variable = {cvar(r)} }}' if a==0 else f'var:{cvar(r)} = {a}'

def row_valid_clause(r,hulls):
    ors=[f'NOT = {{ has_variable = {cvar(r)} }}']
    for idx,h in enumerate(hulls,1):
        ors.append(f'AND = {{ {selected_hull_cond(r,idx)} {provider_gate(h)} {tech_gate(h)} }}')
    return 'OR = { '+' '.join(ors)+' }'

def has_any_clause(rows): return 'OR = { '+' '.join(f'has_variable = {cvar(r)}' for r in rows)+' }'

