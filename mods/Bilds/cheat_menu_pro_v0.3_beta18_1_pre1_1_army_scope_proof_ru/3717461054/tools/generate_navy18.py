    lines=[HEADER.rstrip(),'# beta18-pre3 Fleet Composer 2.0.','## Creation strategy: first non-zero row is the anchor create_military_formation.','## create_military_formation save_temporary_scope_as captures the exact new fleet; remaining rows use create_ship against it.']
