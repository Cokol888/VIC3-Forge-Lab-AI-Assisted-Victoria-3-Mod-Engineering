def load(): return json.loads(REG.read_text(encoding='utf-8'))
def provider_gate(h): return 'cmp_provider_tech_res_active = yes' if h['provider']=='tech_res' else 'always = yes'
def tech_gate(h): return f"has_technology_researched = {h['unlock_technology']}" if h.get('unlock_technology') else 'always = yes'

def generate_sgui(cfg):
    lines=[HEADER.rstrip(),'# beta18-pre2 full naval catalog: one hull + count -> one NEW fleet using marked owned port HQ.']
    for h in cfg['combat_hulls']:
        sid=h['id']; pg=provider_gate(h); tg=tech_gate(h)
        lines.append(f"cmp_navy18_catalog_{sid}_available = {{ scope = country is_shown = {{ {pg} {tg} }} }}")
        for n in cfg['catalog_amounts']:
            lines.append(f"cmp_navy18_catalog_create_{sid}_{n} = {{ scope = country is_valid = {{ {pg} {tg} any_scope_state = {{ has_decree = decree_sakuya_mark_state owner = root has_port_state = yes }} }} effect = {{ cmp_navy18_catalog_create_{sid}_{n}_effect = yes }} }}")
    lines += [
        'cmp_navy18_catalog_result_created = { scope = country is_shown = { var:cmp_navy18_result = 1 } }',
        'cmp_navy18_catalog_result_failed = { scope = country is_shown = { var:cmp_navy18_result = 2 } }',''
    ]
    return '\n'.join(lines)

def generate_effects(cfg):
    lines=[HEADER.rstrip(),'# Catalog creation intentionally creates a NEW formation and never resolves an existing fleet target.']
    for h in cfg['combat_hulls']:
        sid=h['id']; pg=provider_gate(h); tg=tech_gate(h)
        for n in cfg['catalog_amounts']:
            lines += [
                f'cmp_navy18_catalog_create_{sid}_{n}_effect = {{',
                '    remove_variable = cmp_navy18_result',
                '    cmp_navy18_resolve_hq_effect = yes',
                '    if = {',
                f'        limit = {{ {pg} {tg} exists = scope:cmp_navy18_hq_region }}',
                '        create_military_formation = {',
                '            type = fleet',
                '            hq_region = scope:cmp_navy18_hq_region',
                f'            ship = {{ type = ship_type:{h["ship_type"]} count = {n} }}',
                '        }',
                '        set_variable = { name = cmp_navy18_result value = 1 }',
                '    }',
                '    if = { limit = { NOT = { var:cmp_navy18_result = 1 } } set_variable = { name = cmp_navy18_result value = 2 } }',
                '}',
            ]
    lines.append('')
    return '\n'.join(lines)

