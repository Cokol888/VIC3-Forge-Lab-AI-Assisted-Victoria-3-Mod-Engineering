def find_widget(gui, needle):
    pos=gui.find(needle)
    if pos<0: raise RuntimeError(f'needle not found: {needle}')
    start=gui.rfind('widget = {',0,pos)
    if start<0: raise RuntimeError('widget start not found')
    brace=gui.find('{',start); depth=0
    for i in range(brace,len(gui)):
        if gui[i]=='{': depth+=1
        elif gui[i]=='}':
            depth-=1
            if depth==0: return start,i+1
    raise RuntimeError('unclosed widget')

