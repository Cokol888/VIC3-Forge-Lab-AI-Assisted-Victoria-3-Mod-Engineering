def generate_add_effect(delta):
    L=[f"cmp_regions2_build_add_{delta}_effect = {{"]
    for _ in range(delta):
        L.append("  cmp_regions2_build_add_one_guarded_effect = { BUILDING = $BUILDING$ }")
