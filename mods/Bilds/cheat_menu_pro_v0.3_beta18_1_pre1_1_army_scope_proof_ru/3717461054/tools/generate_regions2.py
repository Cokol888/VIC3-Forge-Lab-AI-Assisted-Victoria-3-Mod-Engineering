def selection_condition(item):
    terms=[f"has_variable = {item['selection_variable']}"]
    if item.get('legacy_selection_variable'):
        terms.append(f"has_variable = {item['legacy_selection_variable']}")
    return 'OR = { ' + ' '.join(terms) + ' }' if len(terms)>1 else terms[0]

def selection_or(items):
    return 'OR = { ' + ' '.join(selection_condition(x) for x in items) + ' }'

def exact_gate(rootvar, values):
    return 'OR = { ' + ' '.join(f"var:{rootvar} = {i+1}" for i,_ in enumerate(values)) + ' }'

