def generate_set_effect(target, maxlevel):
    L=[f"cmp_regions2_build_set_{target}_effect = {{"]
    for current in range(maxlevel+1):
        kw='if' if current==0 else 'else_if'
        L += [f"  {kw} = {{",f"    limit = {{ state_has_building_type_levels = {{ target = bt:$BUILDING$ value = {current} }} }}"]
        if current < target:
            for _ in range(target-current):
                L.append("    cmp_regions2_build_add_one_guarded_effect = { BUILDING = $BUILDING$ }")
            L.append(f"    if = {{ limit = {{ state_has_building_type_levels = {{ target = bt:$BUILDING$ value = {target} }} }} root = {{ set_variable = cmp_regions2_any_success }} }}")
        elif current == target:
            L.append("    root = { set_variable = cmp_regions2_any_success }")
        else:
            L.append("    root = { set_variable = cmp_regions2_any_unsafe }")
        L.append("  }")
    L += ["  else = { root = { set_variable = cmp_regions2_any_overflow } }","}"]
    return '\n'.join(L)

