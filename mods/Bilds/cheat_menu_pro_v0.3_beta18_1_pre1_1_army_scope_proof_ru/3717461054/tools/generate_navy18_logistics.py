def outputs():
    cfg=load()
    return {SGUI:generate_sgui(cfg),EFFECT:generate_effects(cfg),LOC_RU:generate_loc(cfg,'russian'),LOC_EN:generate_loc(cfg,'english')}


def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--check',action='store_true'); a=ap.parse_args(); stale=[]
    for p,t in outputs().items():
        enc='utf-8-sig'
        if a.check:
            if not p.exists() or p.read_text(encoding=enc)!=t: stale.append(str(p.relative_to(ROOT)))
        else:
            p.parent.mkdir(parents=True,exist_ok=True); p.write_text(t,encoding=enc)
    if a.check:
        if stale:
            print('STALE: '+', '.join(stale),file=sys.stderr); return 1
        print('PASS: beta18 Final retrofit/logistics codegen is deterministic'); return 0
    print('generated beta18 Final retrofit/logistics SGUI/effects/localization'); return 0

if __name__=='__main__':
    raise SystemExit(main())
