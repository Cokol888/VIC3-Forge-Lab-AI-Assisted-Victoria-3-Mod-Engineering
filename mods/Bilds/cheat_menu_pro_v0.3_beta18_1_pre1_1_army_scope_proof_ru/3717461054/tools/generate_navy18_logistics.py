def generate_effects(cfg:dict)->str:
    amounts=cfg['naval_logistics']['supply_add_amounts']
    L=[HEADER.rstrip(),
       '# Public 1.13 contract: add_supply_ships adds Supply Ships to the scoped country.',
       '# No direct formation assignment or direct ShipTemplate/retrofit write is invented in this file.']
    for n in amounts:
        L += [
          f'cmp_navy18_supply_add_{n}_effect = {{',
          '    remove_variable = cmp_navy18_supply_last_add',
          f'    add_supply_ships = {{ value = {n} }}',
          f'    set_variable = {{ name = cmp_navy18_supply_last_add value = {n} }}',
          '}',
        ]
    L.append('')
    return '\n'.join(L)


